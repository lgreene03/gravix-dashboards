// boundaryCaps returns the display names of core and ee capabilities.
func boundaryCaps(t *testing.T) (core, ee []string) {
	t.Helper()
	raw := repoFile(t, "docs", "oss", "boundary.yaml")

	var name, placement string
	flush := func() {
		if name == "" {
			return
		}
		if placement == "ee" {
			ee = append(ee, name)
		} else if placement == "core" {
			core = append(core, name)
		}
		name, placement = "", ""
	}
	for _, line := range strings.Split(raw, "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(trimmed, "- id:"):
			flush()
		case strings.HasPrefix(trimmed, "name:"):
			name = strings.TrimSpace(strings.TrimPrefix(trimmed, "name:"))
		case strings.HasPrefix(trimmed, "placement:"):
			placement = strings.TrimSpace(strings.TrimPrefix(trimmed, "placement:"))
		}
	}
	flush()

	if len(core) == 0 || len(ee) == 0 {
		t.Fatalf("parsed %d core and %d ee capabilities from boundary.yaml; expected both",
			len(core), len(ee))
	}
	return core, ee
}

// AC-4. The consequence that makes the whole apparatus worth having: a
// capability cannot be moved to ee/ without appearing on the paid list and
// disappearing from the free list on the next commit. Proven by actually moving
// one and regenerating, then restoring.
func TestBoundaryChangeUpdatesBothLists(t *testing.T) {
	root := repoRoot(t)
	boundary := filepath.Join(root, "docs", "oss", "boundary.yaml")
	freePath := filepath.Join(root, "docs-site", "docs", "what-stays-free.md")
	pricingPath := filepath.Join(root, "docs-site", "docs", "pricing.md")

	originals := map[string][]byte{}
	for _, p := range []string{boundary, freePath, pricingPath} {
		body, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("reading %s: %v", p, err)
		}
		originals[p] = body
	}
	t.Cleanup(func() {
		for p, body := range originals {
			_ = os.WriteFile(p, body, 0o644)
		}
	})

	// Pick a real core capability and move it, rather than inventing one — an
	// invented entry would not prove the generator reads the same file the
	// boundary checker does.
	const moved = "ingestion-http"
	src := string(originals[boundary])
	idx := strings.Index(src, "- id: "+moved)
	if idx < 0 {
		t.Fatalf("boundary.yaml no longer has %q; pick another capability", moved)
	}
	rest := src[idx:]
	relPlacement := strings.Index(rest, "placement: core")
	if relPlacement < 0 {
		t.Fatalf("%q is not placement: core", moved)
	}
	mutated := src[:idx] + strings.Replace(rest, "placement: core", "placement: ee", 1)
	if err := os.WriteFile(boundary, []byte(mutated), 0o644); err != nil {
		t.Fatalf("mutating boundary.yaml: %v", err)
	}

	cmd := exec.Command("python3", filepath.Join(root, "scripts", "gen_pricing_page.py"))
	cmd.Dir = root
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("regenerating: %v\n%s", err, out)
	}

	const name = "HTTP fact ingestion"
	newFree, err := os.ReadFile(freePath)
	if err != nil {
		t.Fatalf("re-reading the free page: %v", err)
	}
	if strings.Contains(string(newFree), name) {
		t.Errorf("%q moved to ee but is still on the free page", name)
	}

	newPricing, err := os.ReadFile(pricingPath)
	if err != nil {
		t.Fatalf("re-reading the pricing page: %v", err)
	}
	if !strings.Contains(pricingSection(string(newPricing), "What Gravix Pro adds"), name) {
		t.Errorf("%q moved to ee but did not appear in the paid section", name)
	}
}
