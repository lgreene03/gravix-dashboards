// GRVX-1312. The pricing page is where the charter is easiest to violate, so its
// constraints are the spec. These check the nine acceptance criteria that do not
// need ee/packaging — which is blocked behind GRVX-1305 and, through it, SD-040.
// AC-6, AC-7 and AC-10 need plan definitions that do not exist yet; AC-12 is
// deliberately not implemented (see SD-053). Nothing here asserts a price,
// because no price has been decided.

func pricingPage(t *testing.T) string { return repoFile(t, "docs-site", "docs", "pricing.md") }
func freePage(t *testing.T) string    { return repoFile(t, "docs-site", "docs", "what-stays-free.md") }

// pricingSection returns the body of a `## heading` up to the next `## `.
func pricingSection(page, heading string) string {
	start := strings.Index(page, "## "+heading)
	if start < 0 {
		return ""
	}
	rest := page[start+len("## "+heading):]
	if end := strings.Index(rest, "\n## "); end >= 0 {
		return rest[:end]
	}
	return rest
}

// AC-1. Ordering is the substance: a page that opens with tiers and buries the
// free tier is optimised for conversion rather than for a reader deciding
// whether to trust the project.
func TestFreeSectionFirstAndLargest(t *testing.T) {
	page := pricingPage(t)

	free := strings.Index(page, "## Everything below is free forever")
	paid := strings.Index(page, "## What Gravix Pro adds")
	price := strings.Index(page, "## Pricing\n")

	if free < 0 || paid < 0 {
		t.Fatal("pricing page is missing the free or the paid section")
	}
	if free > paid {
		t.Error("the paid section comes before the free one")
	}
	if price >= 0 && free > price {
		t.Error("the Pricing section comes before the free list")
	}

	freeLen := len(pricingSection(page, "Everything below is free forever"))
	paidLen := len(pricingSection(page, "What Gravix Pro adds"))
	if freeLen <= paidLen {
		t.Errorf("free section is %d bytes and the paid section is %d; the free one must be longest",
			freeLen, paidLen)
	}
}

// AC-2. Both pages come from boundary.yaml, so neither can be edited into
// disagreeing with the code.
func TestPagesGeneratedFromBoundary(t *testing.T) {
	for _, page := range []string{pricingPage(t), freePage(t)} {
		if !strings.Contains(page, "GENERATED by scripts/gen_pricing_page.py") {
			t.Error("page is missing its GENERATED marker; it may have been hand-edited")
		}
	}

	// Every core capability by name must appear on the free page, and every ee
	// capability must not.
	core, ee := boundaryCaps(t)
	free := freePage(t)
	for _, name := range core {
		if !strings.Contains(free, name) {
			t.Errorf("free page omits the core capability %q", name)
		}
	}
	for _, name := range ee {
		if strings.Contains(free, name) {
			t.Errorf("free page lists %q, which is placement: ee", name)
		}
	}
}

// AC-3. A stale page fails, which is what makes AC-2 mean anything.
func TestStalePricingPageFails(t *testing.T) {
	root := repoRoot(t)
	script := filepath.Join(root, "scripts", "gen_pricing_page.py")
	target := filepath.Join(root, "docs-site", "docs", "what-stays-free.md")

	original, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("reading the free page: %v", err)
	}
	t.Cleanup(func() { _ = os.WriteFile(target, original, 0o644) })

	if err := os.WriteFile(target, append(original, []byte("\nhand-edited\n")...), 0o644); err != nil {
		t.Fatalf("staling the page: %v", err)
	}

	cmd := exec.Command("python3", script, "--check")
	cmd.Dir = root
	out, err := cmd.CombinedOutput()
	if err == nil {
		t.Errorf("--check passed on a hand-edited page; it must fail:\n%s", out)
	}
	if !strings.Contains(string(out), "what-stays-free.md") {
		t.Errorf("the failure does not name the stale file:\n%s", out)
	}
}

// AC-5. The commitments are the load-bearing sentences on the page. Checked
// against the spec itself so the page cannot soften them.
func TestCommitmentsVerbatim(t *testing.T) {
	page := pricingPage(t)
	spec := repoFile(t, "docs", "oss", "specs", "GRVX-1312-pro-packaging-and-free-tier-page.md")

	for _, line := range []string{
		"We will never charge for:",
		"reading your own data, by API, by SQL, or by export;",
		"getting your data out, in an open format, at any volume;",
		"authentication, RBAC, two-factor, TLS, or audit logging;",
		"the number of services, hosts, seats, or events you monitor;",
		"how long you keep your own data on your own disk;",
		"the correctness of any number Gravix reports.",
		"That cost us revenue we already had.",
	} {
		if !strings.Contains(spec, line) {
			t.Fatalf("this test is checking a line the spec does not contain: %q", line)
		}
		if !strings.Contains(page, line) {
			t.Errorf("pricing page is missing the commitment line: %q", line)
		}
	}
}

// AC-8. Charter §7.4. An ee/ capability without a licence is absent, not teased.
func TestNoUpsellInProduct(t *testing.T) {
	root := repoRoot(t)
	// Word-bounded. The spec's §8 grep is not, and "Go produced no ..." in
	// dashboards/lib/tco.test.js:117 contains "go pro" as a substring — running
	// that command verbatim reports 1 where the spec expects 0. See SD-053.
	upsell := regexp.MustCompile(`(?i)\bupgrade to pro\b|\bgo pro\b|\bunlock this\b|\bpremium feature\b|\bstart your trial\b`)

	err := filepath.Walk(filepath.Join(root, "dashboards"), func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		body, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		for i, line := range strings.Split(string(body), "\n") {
			if upsell.MatchString(line) {
				rel, _ := filepath.Rel(root, path)
				t.Errorf("charter §7.4: upsell element found at %s:%d", rel, i+1)
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walking dashboards/: %v", err)
	}
}

// AC-9. No core capability may gain a limit introduced by packaging. There is no
// packaging yet, so this asserts the boundary file itself carries no limit
// vocabulary on a core entry — and will keep asserting it once plans exist.
func TestNoArtificialLimitsOnCore(t *testing.T) {
	root := repoRoot(t)
	raw, err := os.ReadFile(filepath.Join(root, "docs", "oss", "boundary.yaml"))
	if err != nil {
		t.Fatalf("reading boundary.yaml: %v", err)
	}

	limit := regexp.MustCompile(`(?i)\b(max_|quota|seat_limit|retention_cap|throttle)\b`)
	if limit.Match(raw) {
		t.Error("boundary.yaml contains limit vocabulary; charter §7.4 forbids an artificial " +
			"limit in the core to make a tier look better")
	}
}

